        let victim = outside.path().join("victim.md");
        std::fs::create_dir_all(dir.path().join("docs")).unwrap();
        use std::os::unix::fs::symlink;
        symlink(&victim, dir.path().join("docs/PRD.md")).unwrap();

        save_consolidated_prd(dir.path(), "generated");

